static int rec_byte(const unsigned char *rec, int off)
{
    return ((rec[off] & 0xF) << 4) | (rec[off + 1] & 0xF);
}
static int blob_val(const unsigned char *rec, int bp)
{
    const unsigned char *b = rec + 16;
    return ((b[2 * bp] & 0xF) << 4) | (b[2 * bp + 1] & 0xF);
}

void juno_apply_reverb(unsigned char *state, const unsigned char *rec)
{
    int level = blob_val(rec, 51);        /* REVERB LEVEL (front-panel blob 51) */
    int time  = rec_byte(rec, 666);       /* REVERB TIME  (NAME3)               */
    uint32_t b; float f;
    b = REVLVL_LUT[level & 0xFF];  memcpy(&f, &b, 4); JF(state, 10759408) = f;
    b = REVTIME_LUT[time  & 0xFF]; memcpy(&f, &b, 4); JF(state, 10759680) = f;
}
