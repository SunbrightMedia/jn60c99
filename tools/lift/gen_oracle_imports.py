#!/usr/bin/env python3
"""gen_oracle_imports.py -- lift/jn_oracle_imports.h: every import NAME the JUNO host oracle answers SPECIALLY, read
mechanically from the oracle's own source (probes/b6/wrapper_emu.py _imp/_gdip, tools/verify/e2e_emu.py _imp), so the
lifted glue (lift/jn_host.c) can never drift from it. The glue mirrors the special answers it implements; any OTHER
special name must TRAP (the oracle does something the glue does not), and only names the oracle does NOT single out
take its defaults (Create* / Open* a new handle, Get* / Query* 0, anything else 0 counted as unhandled).
The prefix rules are part of the dispatch structure, so this tool checks them instead of emitting them: if the oracle
gains or loses a startswith() rule the generator FAILS (a tooth on drift).
usage: python3 tools/lift/gen_oracle_imports.py            (writes lift/jn_oracle_imports.h)"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
SRC = [os.path.join(REPO, 'probes', 'b6', 'wrapper_emu.py'), os.path.join(REPO, 'tools', 'verify', 'e2e_emu.py')]
if os.environ.get('JN_ORACLE_SRC'):                 # the tooth points this at an edited COPY (never the real file)
    SRC = os.environ['JN_ORACLE_SRC'].split(os.pathsep)
OUT = os.path.join(REPO, 'lift', 'jn_oracle_imports.h')
PREFIXES = {'COM:', 'Initialize', 'Gdip', 'Gdiplus', 'Create', 'Open', 'Get', 'Query'}   # the dispatch's prefix rules


def method_bodies(text, names):
    """the source of each `def <name>(` method (to its first dedent to the def's indent or less)"""
    out = []
    lines = text.split('\n')
    for i, ln in enumerate(lines):
        m = re.match(r'(\s*)def (\w+)\(', ln)
        if not m or m.group(2) not in names:
            continue
        ind = len(m.group(1))
        body = []
        for ln2 in lines[i + 1:]:
            if ln2.strip() and len(ln2) - len(ln2.lstrip()) <= ind:
                break
            body.append(ln2)
        out.append('\n'.join(body))
    return out


def main():
    special, prefixes = set(), set()
    for path in SRC:
        for body in method_bodies(open(path).read(), ('_imp', '_gdip')):
            special |= set(re.findall(r'name\s*==\s*[\'"]([^\'"]+)[\'"]', body))
            for grp in re.findall(r'name\s+in\s*\(([^)]*)\)', body):
                special |= set(re.findall(r'[\'"]([^\'"]+)[\'"]', grp))
            prefixes |= set(re.findall(r'name\.startswith\(\s*[\'"]([^\'"]+)[\'"]', body))
    if prefixes != PREFIXES:
        sys.exit('gen_oracle_imports: the oracle\'s prefix rules changed: %s (expected %s) -- update jn_host.c\'s '
                 'dispatch, then this list' % (sorted(prefixes), sorted(PREFIXES)))
    names = sorted(special)
    with open(OUT + '.partial', 'w') as f:
        f.write('/* GENERATED by tools/lift/gen_oracle_imports.py from the oracle\'s own source -- do not edit.\n'
                ' * Every import name the JUNO host oracle (wrapper_emu._imp / _gdip under e2e_emu._imp) answers\n'
                ' * specially; jn_host.c traps on any of these it does not mirror. Sorted (strcmp) for bsearch. */\n')
        f.write('static const char *const JN_ORACLE_SPECIAL[] = {\n')
        for k in range(0, len(names), 4):
            f.write('    ' + ' '.join('"%s",' % n for n in names[k:k + 4]) + '\n')
        f.write('};\n#define JN_ORACLE_NSPECIAL %d\n' % len(names))
    os.replace(OUT + '.partial', OUT)
    print('gen_oracle_imports: %d special names, prefixes %s -> %s' % (len(names), sorted(prefixes), OUT))


if __name__ == '__main__':
    main()
