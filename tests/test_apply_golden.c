/* Wrap one 222-byte blob into a minimal one-record KoaBankFile buffer and apply
 * at index 0 (juno_bank_apply reads only the requested record's blob). */
static int check(const char *name, const unsigned char *blob, const golden_t *g)
{
    /* header(23) + name(16) + blob(222) is enough for record 0. */
    unsigned char bank[23 + 20223];
    /* Full engine state on the heap: juno_bank_apply now also writes the DELAY
     * TYPE selector at state[JUNO_PROG_DLY] (~11 MB in), so the buffer must span
     * the whole engine, not just the low front-panel region. */
    unsigned char *state = calloc(1, JUNO_STATE_BYTES);
    int i, fails = 0;
    if (!state) { printf("alloc failed\n"); return 1; }
    memset(bank, 0, sizeof(bank));
    bank[0] = 'K';                                  /* "KoaBankFile00003" sentinel */
    memcpy(bank + 23 + 16, blob, 222);              /* record 0 blob at +16 */
    /* Embed the VCF CUTOFF FREQ high-res float (big-endian nibbles at record byte
     * 1870) so the applier's cutoff-H override reads it. For patches 0/5/40 the H
     * float equals the coarse cutoff, i.e. the golden off-6736 bits, so encode that. */
    {
        unsigned int hbits = 0;
        for (i = 0; i < NG; ++i) if (g[i].off == 6736) hbits = g[i].bits;
        unsigned char be[4];
        be[0]=(hbits>>24)&0xFF; be[1]=(hbits>>16)&0xFF; be[2]=(hbits>>8)&0xFF; be[3]=hbits&0xFF;
        for (i = 0; i < 4; ++i) {
            bank[23 + 1870 + 2*i]     = (be[i] >> 4) & 0xF;
            bank[23 + 1870 + 2*i + 1] = be[i] & 0xF;
        }
    }
    juno_bank_apply(state, bank, 0);
    for (i = 0; i < NG; ++i) {
        float v = JF(state, g[i].off);
        unsigned int got; memcpy(&got, &v, 4);
        if (got != g[i].bits) {
            printf("  %s off %d: got %08x, expected %08x\n", name, g[i].off, got, g[i].bits);
            ++fails;
        }
    }
    free(state);
    return fails;
}

int main(void)
{
    int fails = 0;
    fails += check("patch0",  BLOB_0,  G0);
    fails += check("patch5",  BLOB_5,  G5);
    fails += check("patch40", BLOB_40, G40);
    if (fails) { printf("FAIL: %d coefficient(s) drifted from the value tree\n", fails); return 1; }
    printf("OK: applier reproduces the plugin value tree bit-for-bit "
           "(3 patches x %d coefficients)\n", NG);
    return 0;
}
