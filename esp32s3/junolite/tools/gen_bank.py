#!/usr/bin/env python3
"""gen_bank.py -- main/jl_bank.h: the plugin's factory bank (truth/presetbankog1.bin, 64 patches), the raw 0..255
panel bytes JUNO LITE uses, read with the proven bank reader (tools/verify/e2e_emu.py). Plumbing only: the bytes are
the plugin's; how JUNO LITE maps them is glue in jl_synth.c (jl_bank_patch). Run: python3 tools/gen_bank.py"""
import os, sys
R = os.path.abspath(os.path.join(os.path.dirname(__file__), '../../..'))
sys.path.insert(0, os.path.join(R, 'tools/verify'))
import e2e_emu as E
F = ['DCO SAW LEVEL', 'DCO PWM LEVEL', 'DCO SUB LEVEL', 'DCO NOISE LEVEL', 'VCF CUTOFF FREQ', 'VCF RESONANCE',
     'VCF ENV MOD', 'VCF KEY FOLLOW', 'HPF CUTOFF FREQ', 'ENV2 ATTACK', 'ENV2 DECAY', 'ENV2 SUSTAIN', 'ENV2 RELEASE',
     'VCA LEVEL', 'EFFECT TYPE', 'EFFECT DEPTH']
L = {nm: bb for p, nm, d, bb in E.load_leaves()}
assert all(f in L for f in F), [f for f in F if f not in L]
b = E.bank_bytes()
rows = []
for i in range(64):
    bl = E.patch_blob(b, i)
    rows.append('    { "%s", { %s } },' % (E.patch_name(b, i).replace('"', "'"), ', '.join(str(E.dec(bl, L[f])) for f in F)))
out = os.path.join(R, 'esp32s3/junolite/main/jl_bank.h')
open(out, 'w').write('/* GENERATED by tools/gen_bank.py from truth/presetbankog1.bin -- do not edit. Fields:\n * '
    + ', '.join(F) + ' */\n#define JL_BANK_N 64\n#define JL_BANK_F %d\nstatic const struct { const char *name; '
    'unsigned char v[JL_BANK_F]; } jl_bank[JL_BANK_N] = {\n' % len(F) + '\n'.join(rows) + '\n};\n')
print('wrote', out)
