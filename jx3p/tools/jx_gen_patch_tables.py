#!/usr/bin/env python3
"""jx_gen_patch_tables.py -- generate jx3p/src/jx_patch_tables.h: the JX-3P plugin's own patch load (its patch
browser's "load", rva 0x335730) as the port applies it (JX-16), from the census jx_patch_census.py writes
(scratchpad/jx_patch/patch_census.pkl; Unicorn there, none here: the two-process rule).

What the census EXECUTED and this file states:
  JX_PATCH_EV[N]   the records one load queues, in their order: the model id, and how its value comes from the
                   record's bytes (the offset from the record's start, its 16-byte name included): INT1X7 the
                   byte; INT2X4 (b0 << 4) | b1; INT4X4 / INT8X4 four / eight bytes OR-ed in, 4 bits apart (the
                   model's set-from-bytes, nothing masked: the JUNO-60's law, gen_state_tables.py); CONST a value
                   no byte of the record carries (the same in every load).
  The ONE decode that reproduces the value of every load (the 64 factory records and the 11 crafted ones); an
  event no decode fits, or more than one, stops the generator -- as does a load whose records differ in kind,
  id or order from the first.
    python3 jx3p/tools/jx_gen_patch_tables.py           write the header
    python3 jx3p/tools/jx_gen_patch_tables.py --check   exit 1 if the committed header differs
"""
import hashlib
import os
import pickle
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
PKL = os.path.join(REPO, 'scratchpad', 'jx_patch', 'patch_census.pkl')
OUT = os.path.join(REPO, 'jx3p', 'src', 'jx_patch_tables.h')
STRIDE, NAME = 20223, 16
DEC = ('JX_DEC_INT1X7', 'JX_DEC_INT2X4', 'JX_DEC_INT8X4', 'JX_DEC_INT4X4', 'JX_DEC_CONST')
WIDTH = (1, 2, 8, 4)


def s32(v):
    v &= 0xFFFFFFFF
    return v - (1 << 32) if v & 0x80000000 else v


def decode(r, o, dec):
    if dec == 0:
        return r[o]
    if dec == 1:
        return (r[o] << 4) | r[o + 1]
    n = 8 if dec == 2 else 4
    v = 0
    for i in range(n):
        v |= r[o + i] << (4 * (n - 1 - i))
    return s32(v)


def derive(loads):
    order = [(q[0], q[2]) for q in loads[0]['queue']]
    if any(k != 2 for k, _ in order):
        raise SystemExit('a load queued a MIDI record (no key was held): not a parameter list')
    for L in loads:
        if [(q[0], q[2]) for q in L['queue']] != order or any(q[1] != 0 for q in L['queue']):
            raise SystemExit('%s: the records differ in kind, id, order or offset from the first load' % L['name'])
        if len(L['record']) != STRIDE:
            raise SystemExit('%s: not a %d-byte record' % (L['name'], STRIDE))
    # the random and position-dependent crafted records first: they reject a wrong offset at once
    rank = sorted(range(len(loads)), key=lambda i: not loads[i]['name'].startswith(('random', 'i*')))
    recs = [loads[i]['record'] for i in rank]
    out = []
    for k, (_, pid) in enumerate(order):
        vals = [loads[i]['queue'][k][3] for i in rank]
        if len(set(vals)) == 1:
            out.append((pid, 0, 4, vals[0]))
            continue
        fits = [(o, dec) for dec in range(4) for o in range(NAME, STRIDE - WIDTH[dec] + 1)
                if all(decode(r, o, dec) == v for r, v in zip(recs, vals))]
        if len(fits) != 1:
            raise SystemExit('record %d (id 0x%x): %d decodes fit %s' % (k, pid, len(fits), fits[:4]))
        out.append((pid, fits[0][0], fits[0][1], 0))
    return out


def header(evs, sha):
    L = ['/* jx_patch_tables.h -- GENERATED by jx3p/tools/jx_gen_patch_tables.py; do not edit.',
         ' *',
         ' * The JX-3P\'s patch load (its patch browser\'s "load", rva 0x335730; JX-16), EXECUTED through the',
         ' * plugin\'s own load (jx3p/tools/jx_patch_census.py: the 64 factory records and 11 crafted ones):',
         ' * the %d records one load queues for the engine, in order -- the model id and how the value comes' % len(evs),
         ' * from the record\'s bytes (the offset from the record\'s start, its 16-byte name included):',
         ' * INT1X7 the byte, INT2X4 (b0 << 4) | b1, INT4X4 / INT8X4 four / eight bytes OR-ed in 4 bits apart',
         ' * (nothing masked), CONST a value no byte of the record carries.',
         ' */',
         '#ifndef JX_PATCH_TABLES_H',
         '#define JX_PATCH_TABLES_H',
         '#include <stdint.h>',
         '#define JX_PATCH_SHA256 "%s"' % sha,
         '#define JX_PATCH_REC_BYTES %du' % STRIDE,
         '#define JX_PATCH_BANK_HEADER 23u',
         'enum { JX_DEC_INT1X7 = 0, JX_DEC_INT2X4 = 1, JX_DEC_INT8X4 = 2, JX_DEC_INT4X4 = 3, JX_DEC_CONST = 4 };',
         'typedef struct { uint32_t id; uint16_t roff; uint8_t dec; int32_t value; } jx_patch_ev;',
         '#define JX_PATCH_EV_N %d' % len(evs),
         'static const jx_patch_ev JX_PATCH_EV[JX_PATCH_EV_N] = {']
    for pid, o, dec, v in evs:
        L.append('    { 0x%08Xu, %du, %s, %d },' % (pid, o, DEC[dec], v))
    L += ['};', '#endif']
    return '\n'.join(L) + '\n'


def main():
    loads = pickle.load(open(PKL, 'rb'))['loads']
    evs = derive(loads)
    sha = hashlib.sha256(b''.join(L['record'] for L in loads)).hexdigest()
    txt = header(evs, sha)
    if '--check' in sys.argv:
        same = os.path.exists(OUT) and open(OUT).read() == txt
        print('jx_gen_patch_tables --check: %s' % ('EQUAL to the committed header' if same else 'DIFFERS -- RED'))
        return 0 if same else 1
    open(OUT, 'w').write(txt)
    print('%s: %d records (%s)' % (OUT, len(evs), ', '.join('%s %d' % (DEC[d][7:], sum(1 for e in evs if e[2] == d))
                                                           for d in range(5) if any(e[2] == d for e in evs))))
    return 0


if __name__ == '__main__':
    sys.exit(main())
