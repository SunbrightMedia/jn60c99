#!/usr/bin/env python3
"""make_native_jx.py -- JX-3P.exe as ONE self-contained Windows program: the C99 port (the sources the JX gates
grade, compiled for Windows) under the plugin's own panel (jx3p/gui/win/jx3p_win.c), with Script.xml, the sprite
sheets, the factory bank and the guest image EMBEDDED as resources. The JUNO-60's tools/dist/make_native.py on the
JX. For the USER'S OWN machine: it holds Roland's artwork (and any of the user's JX banks), so it is written to
scratchpad/ (gitignored) -- never publish it, never commit it.

  scratchpad/dist/native_jx/assets.h   the resource ids (generated)
  scratchpad/dist/native_jx/assets.rc  Script.xml, the sheets, the bank blob, the factory bank, the guest image
  scratchpad/dist/native_jx/banks.rle  "1 Preset" (jx3p/truth/preset_bank_1.bin) + scratchpad/jxbanks/*.bin,
                                       zero-run coded as make_native.py's
  scratchpad/dist/JX-3P.exe            the program

USAGE  python3 jx3p/tools/make_native_jx.py [--define NAME=V ...] [--out EXE] [--jobs N]
       --define / --out: a test build (a check's tooth, -DNAME=V) written to EXE instead
"""
import gzip
import hashlib
import os
import shutil
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(REPO, 'tools', 'dist'))
import make_native as M  # noqa: E402  (rle0, the JUNO's flags and libraries)

TRUTH = os.path.join(REPO, 'jx3p', 'truth')
OUT = os.path.join(REPO, 'scratchpad', 'dist')
BUILD = os.path.join(OUT, 'native_jx')
EXE = os.path.join(OUT, 'JX-3P.exe')
GUEST_GZ = os.path.join(REPO, 'jx3p', 'gen', 'jx_guest_96k.bin.gz')

ID_XML, ID_BANKS, ID_FACTORY, ID_GUEST, ID_PNG0 = 100, 101, 102, 103, 200
SRCS = ['jx3p/gui/win/jx3p_win.c', 'jx3p/gui/jx_bridge.c', 'jx3p/gui/jx_pm_glue.c', 'gui/juno_pm.c',
        'jx3p/src/jx_voice_render.c', 'jx3p/src/jx_voice_helpers.c', 'jx3p/src/jx_master_render.c',
        'jx3p/src/jx_ftz.c']
DEFS = ['-DJX_MEMFS', '-DJPM_PRODUCT="PG-JX3P"']


def verify_truth():
    """every file jx3p/truth/SHA256SUMS pins, the artwork included: its bytes, or nothing is built"""
    n = 0
    for line in open(os.path.join(TRUTH, 'SHA256SUMS')):
        if not line.strip():
            continue
        digest, name = line.split(None, 1)
        name = name.strip()
        got = hashlib.sha256(open(os.path.join(TRUTH, name), 'rb').read()).hexdigest()
        if got != digest:
            raise SystemExit('jx3p/truth/%s: sha256 %s, SHA256SUMS pins %s' % (name, got, digest))
        n += 1
    return n


def bank_list():
    banks = [('1 Preset', os.path.join(TRUTH, 'preset_bank_1.bin'))]
    udir = os.path.join(REPO, 'scratchpad', 'jxbanks')          # the user's JX-3P banks, when given (local only)
    if os.path.isdir(udir):
        for f in sorted(os.listdir(udir)):
            if f.lower().endswith('.bin'):
                banks.append((os.path.splitext(f)[0].lstrip('~').strip(), os.path.join(udir, f)))
    return banks


def main():
    a = sys.argv
    ntruth = verify_truth()
    cc = shutil.which('x86_64-w64-mingw32-gcc')
    rc = shutil.which('x86_64-w64-mingw32-windres')
    if not cc or not rc:
        raise SystemExit('mingw-w64 not found (apt-get install mingw-w64)')
    import fcntl
    os.makedirs(OUT, exist_ok=True)
    lock = open(os.path.join(OUT, 'native_jx.lock'), 'w')     # one build at a time: each empties and refills BUILD
    fcntl.flock(lock, fcntl.LOCK_EX)                          # (two at once broke each other: playbook 263)
    if os.path.exists(BUILD):
        shutil.rmtree(BUILD)
    os.makedirs(BUILD)
    sdir = os.path.join(TRUTH, 'Script')
    pngs = sorted(f for f in os.listdir(sdir) if f.endswith('.png'))
    banks = bank_list()
    with open(os.path.join(BUILD, 'banks.rle'), 'wb') as f:
        f.write(M.banks_blob(banks))
    guest = os.path.join(BUILD, 'jx_guest_96k.bin')
    with gzip.open(GUEST_GZ, 'rb') as g, open(guest, 'wb') as f:
        f.write(g.read())
    with open(os.path.join(BUILD, 'assets.h'), 'w') as f:
        f.write('/* generated by jx3p/tools/make_native_jx.py -- do not edit */\n')
        f.write('#define ASSET_SCRIPT_XML %d\n#define ASSET_BANKS %d\n#define ASSET_FACTORY %d\n#define ASSET_GUEST %d\n'
                % (ID_XML, ID_BANKS, ID_FACTORY, ID_GUEST))
        f.write('static const struct { const char *name; int id; } ASSET_PNG[] = {\n')
        for i, p in enumerate(pngs):
            f.write('    {"%s", %d},\n' % (p, ID_PNG0 + i))
        f.write('};\n#define ASSET_PNG_N %d\n' % len(pngs))
    with open(os.path.join(BUILD, 'assets.rc'), 'w') as f:
        f.write('%d RCDATA "%s"\n' % (ID_XML, M.rc_path(os.path.join(TRUTH, 'Script.xml'))))
        f.write('%d RCDATA "%s"\n' % (ID_BANKS, M.rc_path(os.path.join(BUILD, 'banks.rle'))))
        f.write('%d RCDATA "%s"\n' % (ID_FACTORY, M.rc_path(os.path.join(TRUTH, 'preset_bank_1.bin'))))
        f.write('%d RCDATA "%s"\n' % (ID_GUEST, M.rc_path(guest)))
        for i, p in enumerate(pngs):
            f.write('%d RCDATA "%s"\n' % (ID_PNG0 + i, M.rc_path(os.path.join(sdir, p))))
    res = os.path.join(BUILD, 'assets.res.o')
    subprocess.check_call([rc, '-O', 'coff', '-o', res, os.path.join(BUILD, 'assets.rc')])
    defs = DEFS + ['-D' + a[i + 1] for i, x in enumerate(a[:-1]) if x == '--define']
    exe = a[a.index('--out') + 1] if '--out' in a else EXE
    jobs = int(a[a.index('--jobs') + 1]) if '--jobs' in a else 4
    os.makedirs(os.path.dirname(os.path.abspath(exe)), exist_ok=True)

    cache = os.path.join(OUT, 'native_jx_cache')         # objects by the hash of every file they may include
    os.makedirs(cache, exist_ok=True)
    shared = [os.path.join(REPO, 'jx3p', 'src', f) for f in sorted(os.listdir(os.path.join(REPO, 'jx3p', 'src')))]
    shared += [os.path.join(REPO, f) for f in ('jp8/src/jp8_rt.c', 'jp8/src/jp8_cpu.h', 'gui/juno_pm.h',
                                               'jx3p/gui/jx_bridge.c')]
    shared += [os.path.join(REPO, 'src', f) for f in sorted(os.listdir(os.path.join(REPO, 'src'))) if f.startswith('juno_conv')]

    def compile_one(src):
        h = hashlib.sha256((' '.join([cc] + M.CFLAGS + defs)).encode())
        for f in [os.path.join(REPO, src), os.path.join(BUILD, 'assets.h')] + shared:
            h.update(open(f, 'rb').read())
        obj = os.path.join(cache, '%s_%s.o' % (os.path.basename(src)[:-2], h.hexdigest()[:16]))
        if not os.path.exists(obj):
            subprocess.check_call([cc] + M.CFLAGS + defs + ['-I', BUILD, '-I', os.path.join(REPO, 'jx3p', 'src'),
                                                           '-c', '-o', obj + '.tmp', os.path.join(REPO, src)])
            os.replace(obj + '.tmp', obj)
        return obj
    with ThreadPoolExecutor(jobs) as ex:
        objs = list(ex.map(compile_one, SRCS))
    subprocess.check_call([cc, '-mwindows', '-o', exe] + objs + [res] + M.LIBS + ['-s'])
    print('truth: %d pinned files OK; banks: %s' % (ntruth, ', '.join(n for n, _ in banks)))
    print('wrote %s (%d bytes)%s' % (exe, os.path.getsize(exe), ' with ' + ' '.join(defs[len(DEFS):]) if defs[len(DEFS):] else ''))
    return 0


if __name__ == '__main__':
    sys.exit(main())
