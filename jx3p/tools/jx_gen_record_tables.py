#!/usr/bin/env python3
"""jx_gen_record_tables.py -- generate jx3p/src/jx_record_tables.h (JX-24): JX_DEFAULT_REC, the JX-3P model's record
image at boot as the plugin's own serializer (rva 0x335870) writes it -- the bytes the patch window stores when it
writes a patch before any edit. From scratchpad/jx_record/record_census.pkl (jx_record_census.py, Unicorn only); this
script reads the pickle only (two-process rule).

Checked on the way (else no header): the image after the first block equals the one before it (a block sets no
model value), and every load in the census gave its record's bytes back (a load keeps the bytes as given).

    python3 jx3p/tools/jx_gen_record_tables.py            write the header
    python3 jx3p/tools/jx_gen_record_tables.py --check    exit 1 if the committed header differs
"""
import hashlib
import os
import pickle
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
PKL = os.path.join(REPO, 'scratchpad', 'jx_record', 'record_census.pkl')
OUT = os.path.join(REPO, 'jx3p', 'src', 'jx_record_tables.h')


def header(boot):
    lines = ['/* jx_record_tables.h -- GENERATED by jx3p/tools/jx_gen_record_tables.py from the booted JX-3P plugin',
             ' * (jx_record_census.py). Do not edit.',
             ' *',
             ' * JX_DEFAULT_REC   the model at boot as the plugin serializes it (rva 0x335870 = the JUNO-60\'s 0x335990):',
             ' *                  a record body, %d bytes (sha1 %s) */' % (len(boot), hashlib.sha1(boot).hexdigest()),
             '#ifndef JX_RECORD_TABLES_H',
             '#define JX_RECORD_TABLES_H',
             '#define JX_REC_BODY %du' % len(boot),
             'static const unsigned char JX_DEFAULT_REC[%d] = {' % len(boot)]
    for i in range(0, len(boot), 24):
        lines.append('    ' + ' '.join('%d,' % x for x in boot[i:i + 24]))
    lines += ['};', '#endif', '']
    return '\n'.join(lines)


def main():
    r = pickle.load(open(PKL, 'rb'))
    if r['boot'] != r['boot_after_block']:
        raise SystemExit('the image changed over the first block: the census is not of the model alone')
    for k, body, img in r['loads']:
        if img != body:
            raise SystemExit('load %d did not give its record bytes back' % k)
    text = header(r['boot'])
    if '--check' in sys.argv:
        ok = open(OUT).read() == text
        print('jx_gen_record_tables --check: %s' % ('EQUAL to the committed header' if ok else 'DIFFERS'))
        return 0 if ok else 1
    open(OUT, 'w').write(text)
    print('wrote %s (%d bytes of image, %d nonzero)' % (OUT, len(r['boot']), sum(1 for x in r['boot'] if x)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
